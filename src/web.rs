//! The web UI: two workspaces over one stylesheet and shared scripts, embedded in the binary.
//! "Screens" (`/`) arranges and configures apps; "Devices" (`/devices`) sets up the hardware.

use crate::SharedState;
use axum::Router;
use axum::http::header;
use axum::extract::Path;
use axum::http::StatusCode;
use axum::response::{IntoResponse, Redirect, Response};
use axum::routing::get;

const SCREENS_HTML: &str = include_str!("../web/index.html");
const DEVICES_HTML: &str = include_str!("../web/devices.html");
const LOGIN_HTML: &str = include_str!("../web/login.html");
const APP_CSS: &str = include_str!("../web/app.css");
const UI_JS: &str = include_str!("../web/ui.js");
const SCREENS_JS: &str = include_str!("../web/screens.js");
const APPS_JS: &str = include_str!("../web/apps.js");
const EDITOR_JS: &str = include_str!("../web/editor.js");
const DEVICES_JS: &str = include_str!("../web/devices.js");
const SECURITY_JS: &str = include_str!("../web/security.js");
const AGENT_LINK_JS: &str = include_str!("../web/agent-link.js");
/// The Lua API reference, generated by LDoc (scripts/luadoc.sh).
static LUADOC: include_dir::Dir = include_dir::include_dir!("$CARGO_MANIFEST_DIR/web/luadoc");

const HTML: &str = "text/html; charset=utf-8";
const CSS: &str = "text/css; charset=utf-8";
const JS: &str = "text/javascript; charset=utf-8";

/// One of the UI's own files. They change with the server, so browsers check back each time
/// (`no-cache`) instead of keeping an old page's script.
fn file(content_type: &'static str, body: &'static str) -> impl IntoResponse {
    (
        [
            (header::CONTENT_TYPE, content_type),
            (header::CACHE_CONTROL, "no-cache"),
        ],
        body,
    )
}

pub fn router() -> Router<SharedState> {
    Router::new()
        .route("/", get(|| async { file(HTML, SCREENS_HTML) }))
        .route("/devices", get(|| async { file(HTML, DEVICES_HTML) }))
        .route("/static/ui.js", get(|| async { file(JS, UI_JS) }))
        .route("/static/screens.js", get(|| async { file(JS, SCREENS_JS) }))
        .route("/static/apps.js", get(|| async { file(JS, APPS_JS) }))
        .route("/static/editor.js", get(|| async { file(JS, EDITOR_JS) }))
        .route("/static/devices.js", get(|| async { file(JS, DEVICES_JS) }))
        .route("/static/security.js", get(|| async { file(JS, SECURITY_JS) }))
        .route("/static/agent-link.js", get(|| async { file(JS, AGENT_LINK_JS) }))
        .route("/docs/lua", get(|| async { Redirect::permanent("/docs/lua/") }))
        .route("/docs/lua/", get(|| luadoc(Path(String::new()))))
        .route("/docs/lua/{*path}", get(luadoc))
}

/// What the sign-in page needs, reachable while the lock is on.
pub fn public_router() -> Router<SharedState> {
    Router::new().route("/static/app.css", get(|| async { file(CSS, APP_CSS) }))
}

pub fn login_page() -> impl IntoResponse {
    file(HTML, LOGIN_HTML)
}

async fn luadoc(Path(path): Path<String>) -> Response {
    let path = if path.is_empty() || path.ends_with('/') { format!("{path}index.html") } else { path };
    let Some(f) = LUADOC.get_file(&path) else {
        return StatusCode::NOT_FOUND.into_response();
    };
    let kind = match path.rsplit('.').next() {
        Some("html") => HTML,
        Some("css") => CSS,
        _ => "application/octet-stream",
    };
    ([(header::CONTENT_TYPE, kind), (header::CACHE_CONTROL, "no-cache")], f.contents()).into_response()
}
